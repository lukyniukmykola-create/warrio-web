CREATE OR REPLACE FUNCTION public.warrio_queue_service_notification()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  insert into public.notification_outbox(organization_id, chat_id, kind, title, body)
  select new.organization_id, l.chat_id, 'service_request',
         case when new.source = 'buyer' then 'Нове звернення від покупця' else 'Нове звернення в сервіс' end,
         left(new.title || case when new.contact_note <> '' then E'\nКонтакт: ' || new.contact_note else '' end, 900)
  from public.telegram_links l
  join public.organization_members m on m.organization_id = l.organization_id and m.user_id = l.user_id and m.is_active
  join public.organizations o on o.id = l.organization_id
  where l.organization_id = new.organization_id and l.notify_service
    and (m.role in ('owner', 'admin') or (m.role = 'service_manager' and o.service_manager_enabled));
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.warrio_queue_task_notification()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  insert into public.notification_outbox(organization_id, chat_id, kind, title, body)
  select new.organization_id, l.chat_id, 'work_item', 'Нове завдання', left(new.title, 900)
  from public.telegram_links l
  where l.organization_id = new.organization_id and l.notify_tasks
    and l.user_id = coalesce(new.assigned_user_id, l.user_id)
    and l.user_id is distinct from new.created_by
    and (new.assigned_user_id is not null or exists (
      select 1 from public.organization_members m
      where m.organization_id = l.organization_id and m.user_id = l.user_id and m.is_active and m.role in ('owner', 'admin')));
  return new;
end;
$function$;

