CREATE OR REPLACE FUNCTION public.warrio_enforce_dealer_limit()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  allowed integer;
  used integer;
begin
  if not new.is_active then
    return new;
  end if;
  if tg_op = 'UPDATE' and old.is_active then
    return new;
  end if;
  select o.max_dealers into allowed from public.organizations o where o.id = new.organization_id;
  select count(*)::integer into used from public.dealers d
    where d.organization_id = new.organization_id and d.is_active
      and d.id is distinct from new.id;
  if allowed is not null and used >= allowed then
    raise exception 'dealer_limit_reached' using errcode = '23514';
  end if;
  return new;
end;
$function$;

