CREATE OR REPLACE FUNCTION public.claim_warrio_notifications(p_limit integer DEFAULT 30)
 RETURNS TABLE(id bigint, chat_id bigint, title text, body text)
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
  update public.notification_outbox o
  set attempts = o.attempts + 1
  where o.id in (
    select x.id from public.notification_outbox x
    where x.sent_at is null and x.attempts < 5 and x.created_at > now() - interval '2 days'
    order by x.id limit greatest(1, least(p_limit, 100)) for update skip locked)
  returning o.id, o.chat_id, o.title, o.body;
$function$;

CREATE OR REPLACE FUNCTION public.create_warrio_telegram_link_code(p_organization_id uuid)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  caller uuid := (select auth.uid());
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  code text := '';
  i integer;
begin
  if caller is null then
    raise exception 'authentication_required' using errcode = '42501';
  end if;
  if not exists (
    select 1 from public.organization_members m
    where m.organization_id = p_organization_id and m.user_id = caller and m.is_active
  ) then
    raise exception 'permission_denied' using errcode = '42501';
  end if;
  delete from public.telegram_link_codes where expires_at < now() or user_id = caller;
  for i in 1..8 loop
    code := code || substr(alphabet, 1 + floor(random() * length(alphabet))::int, 1);
  end loop;
  insert into public.telegram_link_codes(code_hash, organization_id, user_id, expires_at)
  values (extensions.digest(code, 'sha256'), p_organization_id, caller, now() + interval '15 minutes');
  return code;
end;
$function$;

