CREATE OR REPLACE FUNCTION public.get_warrio_buyer_service_requests(p_token text)
 RETURNS TABLE(title text, status warrio_service_status, resolution text, created_at timestamp with time zone, closed_at timestamp with time zone)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select r.title, r.status, r.resolution, r.created_at, r.closed_at
  from public.service_requests r
  join public.warranties w on w.id = r.warranty_id and w.organization_id = r.organization_id
  join public.public_warranty_tokens pt on pt.warranty_number = w.warranty_number
  where p_token is not null
    and char_length(p_token) between 16 and 128
    and p_token ~ '^[A-Za-z0-9_-]+$'
    and pt.token_hash = extensions.digest(p_token, 'sha256')
    and w.deleted_at is null
  order by r.created_at desc
  limit 20;
$function$;

CREATE OR REPLACE FUNCTION public.get_warrio_platform_overview()
 RETURNS TABLE(organization_id uuid, name text, slug text, created_at timestamp with time zone, members integer, max_members integer, dealers integer, max_dealers integer, sales integer, warranties integer, open_service_requests integer, last_activity timestamp with time zone)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  if (select auth.uid()) is null then
    raise exception 'authentication_required' using errcode = '42501';
  end if;
  if not public.is_warrio_platform_admin() then
    raise exception 'permission_denied' using errcode = '42501';
  end if;

  return query
  select
    o.id, o.name, o.slug, o.created_at,
    (select count(*)::integer from public.organization_members m
       where m.organization_id = o.id and m.is_active),
    o.max_members,
    (select count(*)::integer from public.dealers d
       where d.organization_id = o.id and d.is_active),
    o.max_dealers,
    (select count(*)::integer from public.sales s
       where s.organization_id = o.id and s.deleted_at is null),
    (select count(*)::integer from public.warranties w
       where w.organization_id = o.id and w.deleted_at is null),
    (select count(*)::integer from public.service_requests r
       where r.organization_id = o.id and r.status in ('new', 'in_progress', 'waiting_parts')),
    (select max(e.created_at) from public.audit_events e where e.organization_id = o.id)
  from public.organizations o
  order by o.created_at desc;
end;
$function$;

