CREATE OR REPLACE FUNCTION public.set_warrio_service_manager_enabled(p_organization_id uuid, p_enabled boolean)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  caller uuid := (select auth.uid());
begin
  if caller is null then
    raise exception 'authentication_required' using errcode = '42501';
  end if;
  if not public.has_org_role(p_organization_id, array['owner']::public.warrio_member_role[]) then
    raise exception 'permission_denied' using errcode = '42501';
  end if;
  if p_enabled is null then
    raise exception 'invalid_value' using errcode = '22023';
  end if;
  update public.organizations
  set service_manager_enabled = p_enabled, updated_at = now()
  where id = p_organization_id;
  insert into public.audit_events(
    organization_id, actor_user_id, event_type, entity_type, entity_id, metadata
  ) values (
    p_organization_id, caller, 'organization.service_manager_toggled', 'organization',
    p_organization_id, jsonb_build_object('enabled', p_enabled)
  );
  return p_enabled;
end;
$function$;

CREATE OR REPLACE FUNCTION public.submit_warrio_service_request(p_token text, p_title text, p_description text DEFAULT ''::text, p_photo_links text[] DEFAULT '{}'::text[], p_contact_note text DEFAULT ''::text)
 RETURNS TABLE(support_email text, support_phone text)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  selected_warranty public.warranties%rowtype;
  selected_org public.organizations%rowtype;
  open_count integer;
  new_id uuid;
begin
  if p_token is null or char_length(p_token) not between 16 and 128 or p_token !~ '^[A-Za-z0-9_-]+$' then
    raise exception 'invalid_token' using errcode = '22023';
  end if;
  if char_length(btrim(coalesce(p_title, ''))) not between 2 and 200
     or char_length(coalesce(p_description, '')) > 4000
     or char_length(coalesce(p_contact_note, '')) > 300 then
    raise exception 'invalid_request' using errcode = '22023';
  end if;
  if char_length(btrim(coalesce(p_contact_note, ''))) < 5 then
    raise exception 'contact_required' using errcode = '22023';
  end if;
  if not public.warrio_valid_photo_links(coalesce(p_photo_links, '{}')) then
    raise exception 'invalid_photo_links' using errcode = '23514';
  end if;

  select w.* into selected_warranty
  from public.warranties w
  join public.public_warranties pw on pw.warranty_number = w.warranty_number
  join public.public_warranty_tokens pt on pt.warranty_number = pw.warranty_number
  where pt.token_hash = extensions.digest(p_token, 'sha256')
    and w.deleted_at is null
  limit 1;
  if selected_warranty.id is null then
    raise exception 'warranty_not_found' using errcode = 'P0002';
  end if;

  select count(*) into open_count
  from public.service_requests r
  where r.warranty_id = selected_warranty.id
    and r.status in ('new', 'in_progress', 'waiting_parts');
  if open_count >= 3 then
    raise exception 'too_many_open_requests' using errcode = '23514';
  end if;

  insert into public.service_requests(
    organization_id, warranty_id, title, description, photo_links,
    contact_note, source, is_warranty_case
  ) values (
    selected_warranty.organization_id, selected_warranty.id,
    btrim(p_title), btrim(coalesce(p_description, '')), coalesce(p_photo_links, '{}'),
    btrim(coalesce(p_contact_note, '')), 'buyer',
    selected_warranty.status::text in ('active_pending_installation', 'active_installed')
      and (selected_warranty.expires_on is null or selected_warranty.expires_on >= current_date)
  ) returning id into new_id;

  insert into public.audit_events(
    organization_id, actor_user_id, event_type, entity_type, entity_id, metadata
  ) values (
    selected_warranty.organization_id, null, 'service_request.created_by_buyer',
    'service_request', new_id, jsonb_build_object('warranty_id', selected_warranty.id)
  );

  select * into selected_org from public.organizations o where o.id = selected_warranty.organization_id;
  return query select selected_org.support_email, selected_org.support_phone;
end;
$function$;

