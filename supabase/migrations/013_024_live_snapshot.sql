CREATE OR REPLACE FUNCTION public.normalize_warrio_values()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
begin
  if tg_table_name = 'organizations' then
    new.slug = lower(trim(new.slug));
  elsif tg_table_name = 'product_models' then
    new.code = upper(trim(new.code));
    new.name = trim(new.name);
  elsif tg_table_name = 'products' then
    new.serial_number = upper(regexp_replace(trim(new.serial_number), '\s+', '', 'g'));
  end if;
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.redeem_warrio_telegram_code(p_code text, p_chat_id bigint, p_username text)
 RETURNS TABLE(linked_org_id uuid, org_name text)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  found_row public.telegram_link_codes%rowtype;
begin
  select * into found_row from public.telegram_link_codes c
  where c.code_hash = extensions.digest(upper(btrim(p_code)), 'sha256') and c.expires_at > now();
  if found_row.user_id is null then
    raise exception 'invalid_code' using errcode = 'P0002';
  end if;
  insert into public.telegram_links(organization_id, user_id, chat_id, username)
  values (found_row.organization_id, found_row.user_id, p_chat_id, left(p_username, 64))
  on conflict on constraint telegram_links_organization_id_user_id_key do update set chat_id = excluded.chat_id, username = excluded.username;
  delete from public.telegram_link_codes where code_hash = found_row.code_hash;
  return query select o.id, o.name from public.organizations o where o.id = found_row.organization_id;
end;
$function$;

